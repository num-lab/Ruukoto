const assert = require('node:assert/strict');
const fs = require('node:fs');
const { spawn, execFileSync } = require('node:child_process');
const { personalCuaLinux } = require('./host.cjs');
(async () => {
 const host = personalCuaLinux();
 const prepared = host.prepare({ command: process.execPath, args: ['-e', "process.stdout.write('ready\\n');setInterval(()=>{},1000)"], env: { PATH: '/usr/bin:/bin' } });
 fs.writeFileSync('planned.json', JSON.stringify({ scope: prepared.scope, description: prepared.description })+'\n');
 const child = spawn(prepared.program.command, prepared.program.args, { env: prepared.program.env, stdio: ['pipe','pipe','pipe'] });
 let stderr=''; child.stderr.on('data', x => stderr+=x);
 const ready = new Promise((resolve,reject) => { child.stdout.once('data', resolve); child.once('exit',(code)=>reject(new Error('early '+code+':'+stderr))); });
 await ready;
 const original = await host.execution(prepared.scope, prepared.description);
 fs.writeFileSync('execution.json',JSON.stringify(original)+'\n');
 assert.equal(await host.stopCli({...original,invocationId:'0'.repeat(32)}),false);
 assert.equal((await host.execution(prepared.scope, prepared.description)).invocationId,original.invocationId);
 const script = "const fs=require('node:fs');const host=require('./host.cjs').personalCuaLinux();host.stopCli(JSON.parse(fs.readFileSync('execution.json'))).then(ok=>{if(!ok)process.exit(2);process.stdout.write('verified\\n')}).catch(e=>{process.stderr.write(e.code+'\\n');process.exit(3)})";
 assert.equal(execFileSync(process.execPath,['-e',script],{encoding:'utf8'}).trim(),'verified');
 assert.equal(await host.stopPrepared(prepared.scope,prepared.description),true);
 fs.writeFileSync('result.json',JSON.stringify({status:'passed',scope:prepared.scope,coldStop:true,wrongInvocationRejected:true,stopped:true})+'\n');
 process.stdout.write(fs.readFileSync('result.json'));
})().catch(e=>{process.stderr.write(String(e.stack)+'\n');process.exitCode=1});
