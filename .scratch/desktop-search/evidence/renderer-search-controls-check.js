async page => {
  const checks = [];
  const record = (name, passed, details) => checks.push({ name, passed, details });
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto('http://127.0.0.1:4318/output/playwright/spotlight.html');
  const search = page.getByRole('button', { name: '搜索 Code 工作区', exact: true });
  const input = page.getByRole('combobox', { name: '搜索 Code 会话与聊天内容' });
  const panel = page.locator('.search-dialog');
  await search.waitFor();
  const buttons = async () => {
    const a = await search.boundingBox();
    const b = await page.getByRole('button', { name: /^(收起|展开)侧栏$/ }).boundingBox();
    return { search: a, sidebar: b, aligned: Math.abs(a.y - b.y) < 1 && a.x + a.width <= b.x && a.x >= 80 };
  };
  record('展开时搜索在侧栏开关左侧，避开原生窗口控制区', (await buttons()).aligned, await buttons());
  await page.evaluate(() => document.addEventListener('animationstart', event => {
    if (event.target.matches('.search-dialog') && event.animationName === 'enter') event.target.getAnimations().forEach(animation => animation.pause());
  }));
  await search.click();
  await input.waitFor();
  const frames = await panel.evaluate(element => {
    const animation = element.getAnimations()[0];
    if (!animation) throw new Error('缺少待验的打开动画');
    animation.pause();
    const duration = animation.effect.getTiming().duration;
    const frames = [0, .5, 1].map(progress => {
      animation.currentTime = duration * progress;
      const box = element.getBoundingClientRect();
      return { progress, x: box.x, y: box.y };
    });
    animation.finish();
    return frames;
  });
  record('打开动画横向不位移、由上向下进入', frames.every(frame => Math.abs(frame.x - frames[2].x) < 1) && frames[0].y < frames[1].y && frames[1].y <= frames[2].y, frames);
  await page.keyboard.press('Meta+k');
  const shortcutClosed = await page.waitForFunction(() => !document.querySelector('.search-dialog'), null, { timeout: 1200 }).then(() => true, () => false);
  record('再次 ⌘K 关闭搜索', shortcutClosed);
  if (!shortcutClosed) await input.press('Escape');
  await panel.waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '搜索 Code 工作区');
  record('关闭后恢复搜索按钮焦点', await search.evaluate(element => element === document.activeElement));
  await page.keyboard.down('Meta');
  await page.keyboard.down('k');
  await input.waitFor();
  await page.keyboard.down('k');
  record('按住快捷键不反复开关', await panel.getAttribute('data-state') === 'open');
  await page.keyboard.up('k');
  await page.keyboard.up('Meta');
  await input.dispatchEvent('compositionstart');
  await page.keyboard.press('Meta+k');
  record('组合输入期间不关闭搜索', await panel.getAttribute('data-state') === 'open');
  await input.dispatchEvent('compositionend');
  await input.fill('当前开发');
  await input.press('Enter');
  await panel.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '收起侧栏', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.app-window').dataset.sidebarOpen === 'false');
  await page.waitForTimeout(250);
  const collapsed = await buttons();
  const tab = await page.getByRole('tab', { name: '当前开发', exact: true }).boundingBox();
  record('收起时搜索在左侧且不覆盖首个标签', collapsed.aligned && tab.x >= collapsed.sidebar.x + collapsed.sidebar.width, { ...collapsed, tab });
  await search.click();
  await input.waitFor();
  await input.press('Escape');
  await panel.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '展开侧栏', exact: true }).click();
  await page.setViewportSize({ width: 400, height: 500 });
  await page.waitForTimeout(250);
  record('窄窗最小侧栏仍保留两个按钮', (await buttons()).aligned, await buttons());
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await search.click();
  record('减少动画偏好仍生效', await panel.evaluate(element => getComputedStyle(element).animationName === 'none'));
  await input.press('Escape');
  await panel.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.keyboard.press('Meta+k');
  record('其他模态窗口不被搜索抢焦点', await page.locator('.settings-dialog').isVisible() && await panel.count() === 0);
  await page.keyboard.press('Escape');
  if (checks.some(check => !check.passed)) throw new Error(JSON.stringify(checks));
  return { passed: true, checks };
}
