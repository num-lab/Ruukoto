async page => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  const focusComposer = async () => { await page.getByRole('dialog').waitFor({ state: 'hidden' }); await page.waitForFunction(() => document.querySelector('.main-canvas textarea') === document.activeElement); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:4318/output/playwright/spotlight.html');
  await page.getByRole('button', { name: '搜索 Code 工作区', exact: true }).click();
  const input = page.getByRole('combobox', { name: '搜索 Code 会话与聊天内容' });
  check(await page.locator('.search-footer').count() === 0, '空查询不显示说明底栏');
  check(await page.getByText('搜索 Code 全部工作区，或打开最近活动的会话。', { exact: true }).count() === 0, '删除空查询说明');
  await input.fill('当前开发');
  await input.press('Enter');
  await focusComposer();
  const composer = page.locator('.main-canvas textarea');
  await composer.waitFor();
  check(await composer.evaluate(element => element === document.activeElement), '名称结果关闭后聚焦输入区');
  await composer.fill('当前会话原草稿');
  await page.getByRole('button', { name: 'Ruukoto', exact: true }).click();
  await page.keyboard.press('Meta+k');
  await input.fill('蓝色灯塔');
  await page.getByRole('option').filter({ hasText: '蓝色灯塔' }).click();
  await focusComposer();
  await composer.waitFor();
  check(await page.getByRole('tab', { name: '古早聊天 已存档' }).getAttribute('aria-selected') === 'true', 'PA 上的正文结果直接切到 Code 原会话');
  check(await composer.evaluate(element => element === document.activeElement && !element.disabled && !element.readOnly), '正文结果保留正常可编辑输入');
  check(await page.getByText('查看历史', { exact: true }).count() === 0, '不出现独立历史栏');
  check(await page.getByText('返回最新', { exact: true }).count() === 0, '不出现返回最新操作');
  check(await page.getByText('正在查看历史，返回最新后继续输入。', { exact: true }).count() === 0, '不出现只读输入提示');
  await composer.fill('存档会话原草稿');
  await page.keyboard.press('Meta+k');
  await input.fill('当前开发');
  await input.press('Enter');
  await focusComposer();
  check(await composer.inputValue() === '当前会话原草稿', '重新打开保留当前会话草稿');
  await page.keyboard.press('Meta+k');
  await input.fill('蓝色灯塔');
  await page.getByRole('option').filter({ hasText: '蓝色灯塔' }).click();
  await focusComposer();
  check(await composer.inputValue() === '存档会话原草稿', '重新打开正文所属会话保留草稿');
  await page.evaluate(() => window.__spotlightReceive({ type: 'event', kind: 'live', event: { seq: 101, sessionId: 'archived', taskId: 'old-task', createdAt: '2026-10-21T00:00:11.000Z', body: { type: 'task.output_fragment', sessionId: 'archived', taskId: 'old-task', messageId: 'live-message', text: '新的实时回复', totalBytes: 18, truncated: false, partial: true, offset: 0 } } }));
  await page.getByText('新的实时回复', { exact: true }).waitFor();
  await page.keyboard.press('Meta+k');
  await input.press('Escape');
  await focusComposer();
  check(await composer.evaluate(element => element === document.activeElement), '取消搜索恢复原输入焦点');
  await page.getByRole('button', { name: '关闭当前开发', exact: true }).focus();
  await page.getByRole('button', { name: '关闭当前开发', exact: true }).press('Enter');
  check(await page.getByRole('tab', { name: '当前开发', exact: true }).count() === 0, '通知前目标标签未打开');
  await page.evaluate(() => window.__spotlightReceive({ type: 'navigate', instanceId: 'synthetic-instance', navigation: { sessionId: 'active', taskId: 'notification-task' } }));
  await page.getByRole('tab', { name: '当前开发', exact: true }).waitFor();
  check(await page.getByRole('tab', { name: '当前开发', exact: true }).getAttribute('aria-selected') === 'true', 'Code 通知仍打开目标新标签');
  const requests = await page.evaluate(() => window.__spotlightRequests);
  check(requests.some(request => request.op === 'read_history' && request.params.session_id === 'archived'), '正文结果读取对应普通会话');
  check(!requests.some(request => request.op === 'read_history' && ('around' in request.params || 'after' in request.params)), '正文结果不创建独立历史导航');
  check(!requests.some(request => request.op === 'set_session_archived'), '显式打开保留存档事实');
  check(errors.length === 0, '无 renderer 异常');
  return { passed: true, flows: ['名称结果', 'PA 上正文结果', '存档标识', '普通输入与焦点', '两会话草稿', '实时回复', 'Esc 焦点恢复', 'Code 通知新标签'], historyRequests: requests.filter(request => request.op === 'read_history'), errors };
}
