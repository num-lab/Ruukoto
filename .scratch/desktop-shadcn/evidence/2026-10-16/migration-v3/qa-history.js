async (page) => {
  page.setDefaultTimeout(10000);
  const check = (value, message) => { if (!value) throw new Error(message); };
  const open = async button => { if (await button.getAttribute('aria-expanded') !== 'true') await button.click(); await page.waitForTimeout(230); };
  const evidence = '/Users/eitrous/.codex/worktrees/desktop-write-patch/ruukoto/.scratch/desktop-shadcn/evidence/2026-10-16/migration-v3/output/playwright';
  await page.setViewportSize({ width: 1280, height: 827 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  const main = page.getByRole('region', { name: '会话消息', exact: true });
  await page.locator('.workspace-session').filter({ hasText: 'gui-files:' }).click();
  await open(main.getByRole('button', { name: /failed.*Read files/ }));
  const read = main.getByRole('link', { name: '打开文件 src/lib/sync/indexeddb.ts', exact: true });
  check(await read.evaluate(el => !el.closest('button')), 'Read 路径被嵌套在可展开工具按钮内');
  await read.click();
  const source = page.getByRole('region', { name: '文件源码', exact: true });
  await source.getByText('export const clock = 2;', { exact: true }).waitFor();
  check(await source.locator('.hljs-keyword').count() > 0, '真实文件源码没有语法高亮');
  await page.screenshot({ path: evidence + '/read-file-highlight.png' });
  await open(main.getByRole('button', { name: 'Edited src/lib/sync/indexeddb.ts', exact: true }));
  await main.locator('[data-slot=code-block-line][data-variant=removed]').filter({ hasText: 'clock = 1' }).waitFor();
  await main.locator('[data-slot=code-block-line][data-variant=added]').filter({ hasText: 'clock = 2' }).waitFor();
  await open(main.getByRole('button', { name: 'Wrote src/components/PassTimeline.tsx', exact: true }));
  await main.locator('[data-slot=code-block-line][data-variant=removed]').filter({ hasText: "'Online'" }).waitFor();
  await main.locator('[data-slot=code-block-line][data-variant=added]').filter({ hasText: "'Offline'" }).waitFor();
  await page.screenshot({ path: evidence + '/inline-edit-write.png' });
  await open(main.getByRole('button', { name: /^Failed to run printf 'QA_TOOL_FAILURE/ }));
  await main.locator('[data-slot=code-block][data-variant=destructive]').filter({ hasText: 'Command exited with code 17' }).waitFor();
  const failed = main.locator('[data-slot=trace-line][data-status=error]').filter({ hasText: 'Failed to run' });
  check(await failed.evaluate(el => getComputedStyle(el).color !== getComputedStyle(document.querySelector('.main-canvas')).color), '失败工具没有红色状态');
  const missing = main.getByRole('link', { name: '打开文件 missing.txt', exact: true });
  check(await missing.evaluate(el => !el.closest('button')), '失败 Read 出现折叠按钮');
  await main.locator('[data-slot=code-block][data-variant=destructive]').filter({ hasText: /missing\.txt/ }).waitFor();
  await page.screenshot({ path: evidence + '/failed-tools.png' });
  await open(main.getByRole('button', { name: /^Ran # LONG_COMMAND_START/ }));
  await page.waitForFunction(() => [...document.querySelectorAll('.stream-scroll [data-slot=code-block-content]')].some(el => el.textContent.length > 80000 && el.textContent.includes('LONG_COMMAND_END')));
  const long = await main.locator('[data-slot=code-block-content]').allTextContents();
  const command = long.find(text => text.length > 80000);
  check(command?.includes('command-padding-'.repeat(6000)), 'Bash 完整参数没有跨页读取');
  check(command?.endsWith('LONG_COMMAND_END\n') || command?.includes('\nLONG_COMMAND_END'), 'Bash 输出缺失');
  check(!(await main.innerText()).includes('Thought for'), '消息流仍显示思维链');
  return { readFile: true, highlightedSource: true, editPatch: true, overwriteWritePatch: true, failedBashRed: true, failedReadStatic: true, completeCommandChars: command?.length, thoughtHidden: true };
}
