async (page) => {
  page.setDefaultTimeout(10000);
  const check = (value, message) => { if (!value) throw new Error(message); };
  const evidence = '/Users/eitrous/.codex/worktrees/desktop-write-patch/ruukoto/.scratch/desktop-shadcn/evidence/2026-10-16/migration-v3/output/playwright';
  await page.setViewportSize({ width: 1280, height: 827 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  if (await page.locator('#workspace-filter').getAttribute('data-open') === 'true') await page.getByRole('textbox', { name: '筛选工作区与会话', exact: true }).press('Escape');
  await page.locator('.workspace-session').filter({ hasText: 'gui-live-session' }).click();
  await page.locator('.workspace-session').filter({ hasText: 'gui-files:' }).click();
  await page.waitForTimeout(240);
  const tabs = page.locator('.center-tabs .tab-group');
  const tab = tabs.filter({ hasText: 'gui-live-session' });
  await page.mouse.move(700, 500);
  const before = await tab.boundingBox();
  check(await tab.locator('.tab-close').evaluate(el => getComputedStyle(el).opacity) === '0', '未 hover 的关闭键可见');
  await tab.hover();
  const after = await tab.boundingBox();
  check(Math.abs(before.width - after.width) < 0.01, 'hover 为关闭键额外腾出宽度');
  check(await tab.locator('.tab-close').evaluate(el => Number(getComputedStyle(el).opacity)) > 0, 'hover 关闭键未叠加');
  check(await tab.locator('.center-tab > span').evaluate(el => getComputedStyle(el).maskImage !== 'none'), 'hover 文本没有渐变');
  await page.screenshot({ path: evidence + '/tab-hover-dark.png' });
  const separators = await page.locator('.center-tabs .tab-group:has(> [data-state=active])').evaluate(el => ({ left: getComputedStyle(el, '::before').display, right: el.nextElementSibling ? getComputedStyle(el.nextElementSibling, '::before').display : 'none' }));
  check(separators.left === 'none' && separators.right === 'none', '选中 tab 两端仍有分隔线');
  const rightToggle = page.getByRole('button', { name: '展开右栏', exact: true });
  if (await rightToggle.count()) await rightToggle.click();
  check(await page.locator('.inspector-header').evaluate(el => getComputedStyle(el, '::before').height) === '28px', '两区分隔线不是居中的 28px 短线');
  await page.evaluate(() => {
    window.__qaMotion = [];
    document.addEventListener('animationstart', event => {
      if (!['demo-expand', 'demo-collapse'].includes(event.animationName)) return;
      const el = event.target;
      const record = { name: event.animationName, duration: getComputedStyle(el).animationDuration, heights: [] };
      window.__qaMotion.push(record);
      const started = performance.now();
      const sample = () => { record.heights.push(el.getBoundingClientRect().height); if (performance.now() - started < 220) requestAnimationFrame(sample); };
      sample();
    });
  });
  const workspace = page.locator('.workspace-row > button').filter({ hasText: 'fumotravel-web' });
  await workspace.click();
  await page.waitForTimeout(240);
  await workspace.click();
  await page.waitForTimeout(240);
  const group = page.getByRole('region', { name: '会话消息', exact: true }).getByRole('button', { name: /failed.*Read files/ });
  const initially = await group.getAttribute('aria-expanded');
  await group.click(); await page.waitForTimeout(240);
  await group.click(); await page.waitForTimeout(240);
  check(await group.getAttribute('aria-expanded') === initially, '工具组开关不能恢复原状态');
  const motions = await page.evaluate(() => window.__qaMotion);
  check(motions.some(m => m.name === 'demo-expand' && new Set(m.heights.map(h => h.toFixed(1))).size > 3), '未检测到实际展开过渡');
  check(motions.some(m => m.name === 'demo-collapse' && new Set(m.heights.map(h => h.toFixed(1))).size > 3), '未检测到实际收起过渡');
  const filter = page.getByRole('button', { name: '筛选工作区与会话', exact: true });
  await page.evaluate(() => { window.__qaFilterHeights = []; const el = document.querySelector('#workspace-filter'); const started = performance.now(); const sample = () => { window.__qaFilterHeights.push(el.getBoundingClientRect().height); if (performance.now() - started < 400) requestAnimationFrame(sample); }; sample(); });
  await filter.click();
  await page.getByRole('textbox', { name: '筛选工作区与会话', exact: true }).fill('nexus');
  await page.waitForTimeout(240);
  check(await page.locator('.workspace-row > button[aria-expanded]').count() === 1, '工作区过滤结果不符');
  await page.getByRole('textbox', { name: '筛选工作区与会话', exact: true }).press('Escape');
  await page.waitForTimeout(240);
  check(await filter.evaluate(el => el === document.activeElement), 'Escape 未归还筛选按钮焦点');
  check(new Set(await page.evaluate(() => window.__qaFilterHeights.map(h => h.toFixed(1)))).size > 3, '筛选框没有高度过渡');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await workspace.click();
  await workspace.click();
  check(await page.locator('.workspace-collapse').first().evaluate(el => getComputedStyle(el).animationName) === 'none', '减弱动画未禁用折叠动画');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 833, height: 827 });
  const y = await page.locator('.composer-actions > div').evaluateAll(elements => elements.map(el => el.getBoundingClientRect().y));
  check(Math.abs(y[0] - y[1]) < 5, '窄栏底部按钮换行');
  check(await page.locator('.model-selector-name').evaluate(el => getComputedStyle(el).display) === 'none', '窄栏模型未收成 brain 图标');
  await page.screenshot({ path: evidence + '/narrow-dark.png' });
  await page.setViewportSize({ width: 1280, height: 827 });
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('combobox', { name: '主题', exact: true }).click();
  await page.getByRole('option', { name: '浅色', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  await page.screenshot({ path: evidence + '/light.png' });
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('combobox', { name: '主题', exact: true }).click();
  await page.getByRole('option', { name: '深色', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  return { tabOverlayAndFade: true, selectedSeparatorsHidden: true, shortDivider: true, motionEvents: motions.map(m => ({ name: m.name, duration: m.duration, sampledHeights: m.heights.length })), filterTransitionAndFocus: true, reducedMotion: true, narrowSingleRow: true, lightAndDark: true };
}
