import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawn, spawnSync } from 'node:child_process';
import { once } from 'node:events';
import { setTimeout as delay } from 'node:timers/promises';
import { openPersonalHarness } from '../../../../../apps/ruukoto/src/personal-harness.ts';
import { personalProvider } from '../../../../../apps/ruukoto/src/personal-model.ts';
import { ServiceInspectionAdmission } from '../../../../../apps/ruukoto/src/personal-service-inspection.ts';
import { MockModelServer } from '../../../../../test/helpers/mock-provider.ts';
const repo=path.resolve(import.meta.dirname,'../../../../../');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'rk-admission-before-spawn-'));
const unit='audit.service'; const helper=path.join(root,'helper');
fs.mkdirSync(helper); fs.mkdirSync(path.join(helper,'units'));
fs.copyFileSync(path.join(repo,'test/helpers/fake-service-helper.mjs'),path.join(helper,'helper.mjs'));
fs.writeFileSync(path.join(helper,'services.json'),JSON.stringify({machineId:'audit-machine',inspectUid:1,inspectGid:1,services:{[unit]:{actions:['restart']}}}));
fs.writeFileSync(path.join(helper,'units',unit),'[Service]\nExecStart=/usr/bin/true\n');
fs.writeFileSync(path.join(helper,'state.json'),JSON.stringify({[unit]:{loadState:'loaded',activeState:'active',subState:'running',mainPid:1,invocationId:'audit',result:'success',activeEnterTimestamp:'now'}}));
const server=new MockModelServer((_request,index)=>index===0?{kind:'tool_calls',calls:[{id:'inspect',name:'service_inspect',arguments:{unit}}]}:{kind:'text',text:'done'});
const marker=path.join(root,'admission-committed');
const calls=()=>fs.existsSync(path.join(helper,'calls.log'))?fs.readFileSync(path.join(helper,'calls.log'),'utf8').trim().split('\n').map(JSON.parse):[];
const context={};
process.env.RUUKOTO_ADMISSION_AUDIT_KEY='test-only';
let child; let personal; let stderr='';
try {
  const config={api:'openai-completions',baseUrl:await server.start(),modelId:'mock-model',apiKeyEnv:'RUUKOTO_ADMISSION_AUDIT_KEY',contextWindow:128000,maxTokens:1024};
  const service={helperPath:path.join(helper,'helper.mjs'),policyPath:path.join(helper,'services.json'),sudoPath:'/usr/bin/sudo',useSudo:false,timeouts:{inspectMs:2000,stopMs:1000}};
  const directory=path.join(root,'profile');
  const script=`import fs from 'node:fs'; import {openPersonalHarness} from './apps/ruukoto/src/personal-harness.ts'; import {personalProvider} from './apps/ruukoto/src/personal-model.ts'; import {openNodeSqliteStorage} from '@earendil-works/pi-durable/storage/sqlite/node'; const {directory,config,service,marker}=JSON.parse(process.env.RUUKOTO_ADMISSION_AUDIT); const p=await openPersonalHarness({directory,provider:personalProvider(config),modelId:config.modelId,service,openStorage:async filename=>{const storage=await openNodeSqliteStorage(filename);const commit=storage.commit.bind(storage); storage.commit=async(writes,context)=>{const result=await commit(writes,context);if(writes.some(write=>write.type==='entry'&&write.value.kind==='ruukoto.service-inspection-admission')){fs.writeFileSync(marker,'');await new Promise(()=>{});}return result;};return storage;}});await p.submit('inspect','admission-crash');setInterval(()=>{},1000);`;
  child=spawn(process.execPath,['--import','tsx','--input-type=module','--eval',script],{cwd:repo,env:{...process.env,RUUKOTO_ADMISSION_AUDIT:JSON.stringify({directory,config,service,marker})},stdio:['ignore','ignore','pipe']});
  child.stderr.on('data',chunk=>{stderr+=chunk.toString();});
  const deadline=Date.now()+10000;
  while(!fs.existsSync(marker)){assert.ok(Date.now()<deadline,stderr||'admission not committed');await delay(10);}
  assert.deepEqual(calls(),[],'inspection must not spawn before admission commit returns');
  const exited=once(child,'exit'); child.kill('SIGKILL'); await exited;
  personal=await openPersonalHarness({directory,provider:personalProvider(config),modelId:config.modelId,service});
  assert.equal(await personal.answer('inspect','admission-crash'),'done');
  const admissions=(await personal.main.entries({order:'ascending'},256,undefined,context)).items.filter(ServiceInspectionAdmission.is);
  assert.equal(admissions.length,2);
  const original=admissions[0].data.inspectionId; const next=admissions[1].data.inspectionId;
  assert.notEqual(original,next);
  assert.equal(calls()[0][0],'stop-inspect'); assert.equal(calls()[0][1],original);
  assert.deepEqual(calls().filter(call=>call[0]==='inspect-op').map(call=>call[1]),[next]);
  const claim=JSON.parse(fs.readFileSync(path.join(helper,'inspections',original,'claim.json'),'utf8'));
  assert.equal(claim.stoppedFirst,true);
  const late=spawnSync(process.execPath,[service.helperPath,'inspect-op',original,'audit-machine',unit],{encoding:'utf8'});
  assert.equal(late.status,64); assert.match(late.stderr,/already_claimed/);
  assert.equal((await personal.inspections.list()).length,0);
  process.stdout.write(JSON.stringify({admissionCommittedBeforeKill:true,inspectSpawnsBeforeKill:0,startupStoppedOriginal:true,newAttemptOnly:true,lateOriginalRefused:true,pending:0})+'\n');
} finally {
  if(child?.exitCode===null&&child?.signalCode===null) child.kill('SIGKILL');
  await personal?.close(); await server.close(); fs.rmSync(root,{recursive:true,force:true}); delete process.env.RUUKOTO_ADMISSION_AUDIT_KEY;
}
