import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawn } from 'node:child_process';
const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'review-delayed-cwd-')));
const workspace = path.join(root, 'work');
fs.mkdirSync(workspace);
const { dev, ino } = fs.statSync(workspace);
const child = spawn(process.execPath, [path.resolve(process.argv[2])], { cwd: workspace, stdio: ['pipe', 'pipe', 'pipe'] });
let stderr = '';
child.stderr.on('data', data => stderr += data);
const done = new Promise(resolve => child.on('close', code => resolve({ code, stderr })));
await new Promise((resolve, reject) => child.stdin.write(JSON.stringify({ command: 'touch invoked', workspace: { path: workspace, dev, ino } }) + ' '.repeat(1024 * 1024), error => error ? reject(error) : resolve()));
await new Promise(resolve => setTimeout(resolve, 400));
fs.renameSync(workspace, path.join(root, 'original'));
fs.mkdirSync(workspace);
child.stdin.end();
console.log(JSON.stringify({ ...await done, oldInvoked: fs.existsSync(path.join(root, 'original', 'invoked')), newInvoked: fs.existsSync(path.join(workspace, 'invoked')) }));
fs.rmSync(root, { recursive: true, force: true });
