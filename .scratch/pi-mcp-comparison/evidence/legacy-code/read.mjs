/** 用最终 1.3.0 宿主与 provider 读取旧隔离档案，验证原前缀和图片。 */
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const source = process.argv[2];
const require = createRequire(path.join(source, 'package.json'));
const installed = path.join(path.dirname(require.resolve('@earendil-works/pi-coding-agent')), '..', 'package.json');
assert.equal(JSON.parse(fs.readFileSync(installed, 'utf8')).version, '1.3.0');
const fromPackage = name => import(pathToFileURL(require.resolve(name)).href);
const fromSource = name => import(pathToFileURL(path.join(source, name)).href);
const { Runtime } = await fromPackage('@ruukoto/runtime/runtime.ts');
const { Db } = await fromPackage('@ruukoto/core/db.ts');
const { Store } = await fromPackage('@ruukoto/core/store.ts');
const { ArtifactStore } = await fromPackage('@ruukoto/agent/artifacts.ts');
const { parseSessionFile } = await fromPackage('@ruukoto/core/history.ts');
const { openPiSessionManager } = await fromPackage('@ruukoto/agent/session-factory.ts');
const { imageReferenceView, restoreImageInput } = await fromPackage('@ruukoto/agent/inbound-images.ts');
const { createMockTools } = await fromPackage('@ruukoto/agent/mock-tools.ts');
const { product } = await fromSource('apps/ruukoto-code/src/product.ts');
const { MockModelServer } = await fromSource('test/helpers/mock-provider.ts');
const { writeModelsJson, waitFor } = await fromSource('test/helpers/testkit.ts');
const d = JSON.parse(fs.readFileSync('/tmp/ruukoto-code-review-old-history.json', 'utf8'));
const before = fs.readFileSync(d.file);
assert.equal(createHash('sha256').update(before).digest('hex'), d.sha256);
const manager = openPiSessionManager(d.session, path.dirname(d.file));
const context = manager.buildSessionContext();
const history = parseSessionFile(d.file);
assert.ok(context.messages.some(message => message.role === 'toolResult' && message.toolName === 'mcp_mock_capture'));
assert.ok(history.some(entry => entry.type === 'message' && entry.message?.role === 'toolResult' && entry.message?.toolName === 'mcp_mock_capture'));
assert.deepEqual(fs.readFileSync(d.file), before);
const db = new Db(d.dirs.dataDir), store = new Store(db), artifacts = new ArtifactStore(d.dirs.dataDir, store);
const messages = restoreImageInput(imageReferenceView(context.messages, d.session.id), artifacts, store);
assert.ok(messages.some(message => message.role === 'toolResult' && message.toolName === 'mcp_mock_capture' && message.content.some(part => part.type === 'image' && part.data === d.png)));
assert.deepEqual(fs.readFileSync(d.file), before);
db.close();
const server = new MockModelServer(() => ({ kind: 'text', text: '新版读取旧图完成' }));
const baseUrl = await server.start();
await writeModelsJson(d.dirs, baseUrl);
let runtime;
try {
  runtime = await Runtime.start({ product: product.runtime, dataDir: d.dirs.dataDir, agentDir: d.dirs.agentDir, socketPath: path.join(d.dirs.root, 'new.sock'), thinkingLevel: 'off', modelProvider: 'mock', modelId: 'mock-model', toolFactory: ctx => createMockTools(ctx), mcp: { connectTimeoutMs: 50, listTimeoutMs: 50 } });
  const resolve = runtime.models.current.modelCatalog.resolve.bind(runtime.models.current.modelCatalog);
  runtime.models.current.modelCatalog.resolve = async selection => ({ ...await resolve(selection), input: ['text', 'image'] });
  const task = await runtime.submit({ sessionId: d.session.id, requestId: 'new-read-old-history', input: '读取之前的图，仅报告', modelSelection: runtime.defaultSelection });
  await waitFor('新版任务终结', () => ['completed', 'failed', 'interrupted', 'canceled'].includes(runtime.store.getTask(task.id).status));
  assert.equal(runtime.store.getTask(task.id).status, 'completed', runtime.store.getTask(task.id).interruptReason);
  assert.ok(JSON.stringify(server.calls).includes(`data:image/png;base64,${d.png}`));
  const after = fs.readFileSync(d.file);
  assert.deepEqual(after.subarray(0, before.length), before);
  assert.ok(after.toString().includes('mcp_mock_capture'));
  const result = { oldVersion: d.version, currentVersion: '1.3.0', beforeBytes: before.length, beforeSha256: d.sha256, afterBytes: after.length, oldPrefixUnchanged: true, oldToolNameUnchanged: true, imageRestoredToNewProvider: true, newProviderCalls: server.calls.length };
  fs.writeFileSync('/tmp/ruukoto-code-review-old-history-result.json', JSON.stringify(result, null, 2) + '\n');
  console.log(JSON.stringify(result));
} finally { await runtime?.stop('old-history-read-complete'); await server.close(); }
